  `period` int(11) NOT NULL DEFAULT 0,
  `ttype` varchar(50) DEFAULT NULL,
  `staked` decimal(28,8) NOT NULL DEFAULT 0.00000000,
  `status` int(11) NOT NULL DEFAULT 0,
